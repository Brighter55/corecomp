def expand_origins(origins_str):
    origins = set()
    for raw in origins_str.split(","):
        o = raw.strip()
        if not o:
            continue
        origins.add(o)
        if "://www." in o:
            origins.add(o.replace("://www.", "://"))
        else:
            scheme, domain = o.split("://", 1)
            origins.add(f"{scheme}://www.{domain}")
    return list(origins)
